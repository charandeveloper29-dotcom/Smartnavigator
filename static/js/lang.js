/* ── Core translation engine ── */
function applyTranslation(lang) {
  const t = TRANSLATIONS[lang] || TRANSLATIONS.en;
  window.SN_LANG = lang;
  window.SN_T    = t;
  localStorage.setItem('sn_lang', lang);

  /* text content */
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const v = t[el.getAttribute('data-i18n')];
    if (v !== undefined) el.textContent = v;
  });

  /* innerHTML (allows <br>) */
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const v = t[el.getAttribute('data-i18n-html')];
    if (v !== undefined) el.innerHTML = v.replace(/\n/g,'<br>');
  });

  /* placeholders */
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const v = t[el.getAttribute('data-i18n-placeholder')];
    if (v !== undefined) el.placeholder = v;
  });

  /* select options */
  document.querySelectorAll('[data-i18n-opt]').forEach(el => {
    el.querySelectorAll('option[data-i18n]').forEach(opt => {
      const v = t[opt.getAttribute('data-i18n')];
      if (v !== undefined) opt.textContent = v;
    });
  });

  /* html lang attribute */
  document.documentElement.lang = lang;
}

function t(key) {
  const lang = window.SN_LANG || localStorage.getItem('sn_lang') || 'en';
  return (TRANSLATIONS[lang]||TRANSLATIONS.en)[key] || TRANSLATIONS.en[key] || key;
}

/* ── Auto-apply saved language on every page load ── */
(function() {
  const saved = localStorage.getItem('sn_lang') || 'en';
  window.SN_LANG = saved;
  window.SN_T    = TRANSLATIONS[saved] || TRANSLATIONS.en;
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => applyTranslation(saved));
  } else {
    applyTranslation(saved);
  }
})();
